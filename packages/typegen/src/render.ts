import type { CatalogSchema } from '@0disoft/saylo-core';

export type TypeSchema = Pick<CatalogSchema, 'namespace' | 'keys' | 'richTextTags'>;
const quote = (value: string) => JSON.stringify(value).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');

/** Required arguments follow the base schema, including arguments from every ICU branch. */
export function renderTypes(schemas: readonly TypeSchema[]): string {
  const lines = ['// Generated by Saylo. Do not edit.', 'export type AppSchema = {'];
  const richLines: string[] = [];
  const seen = new Set<string>();
  for (const schema of [...schemas].sort((a, b) => a.namespace < b.namespace ? -1 : a.namespace > b.namespace ? 1 : 0)) {
    if (seen.has(schema.namespace)) throw new Error(`Duplicate namespace: ${schema.namespace}`);
    seen.add(schema.namespace);
    for (const id of Object.keys(schema.keys).sort()) {
      const args = schema.keys[id]!;
      const properties = Object.keys(args).sort().map(name => {
        const types = [...new Set(args[name]!.acceptedTypes.map(type => type === 'date' ? 'Date' : type))].sort();
        if (!types.length) throw new Error(`Argument ${name} has no accepted types.`);
        return `${quote(name)}: ${types.join(' | ')};`;
      });
      lines.push(`  ${quote(`${schema.namespace}:${id}`)}: ${properties.length ? `{ ${properties.join(' ')} }` : '{}'};`);
      if (schema.richTextTags && Object.hasOwn(schema.richTextTags, id)) {
        const tags = [...new Set(schema.richTextTags[id]!)].sort();
        richLines.push(`  ${quote(`${schema.namespace}:${id}`)}: ${tags.map(quote).join(' | ') || 'never'};`);
      }
    }
  }
  const richSchema = richLines.length ? `\nexport type AppRichTextSchema = {\n${richLines.join('\n')}\n};\n` : '';
  return `${lines.join('\n')}\n};\n${richSchema}`;
}
